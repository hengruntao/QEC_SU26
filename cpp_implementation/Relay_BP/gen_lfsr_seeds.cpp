/* gen_lfsr_seeds.cpp -- testbench-side tool, NOT part of the HLS design.
   Writes Relay_BP/relay_lfsr_seeds.h: the 144 per-VNU 8-bit LFSR start states that
   rng_seed_all(states, GLOBAL_SEED) produces (leap-ahead seeding on the 255-state cycle,
   vnu/RNG.cpp). decode_relay() loads these constants into the VNU LFSRs before leg 0,
   so the synthesized design never runs rng_seed_all().
   Checks before writing: every state is non-zero and the 144 states are all different.

   Build and run from cpp_implementation\ :
     g++ -std=c++11 -I<path to ap_int headers> Relay_BP/gen_lfsr_seeds.cpp vnu/RNG.cpp -o gen_lfsr_seeds
     ./gen_lfsr_seeds 0 > Relay_BP/relay_lfsr_seeds.h          (argument = global seed, 0..255;
                                                                 0 = default start state 0xA5)
*/
#include <cstdio>
#include <cstdlib>
#include "../vnu/RNG.h"

int main(int argc, char **argv)
{
    unsigned global_seed = (argc > 1) ? (unsigned)strtoul(argv[1], 0, 0) : 0u;
    if (global_seed > 255) {
        fprintf(stderr, "global seed must be 0..255 (8-bit LFSR)\n");
        return 1;
    }
    qec_lfsr_t states[QEC_NUM_VARIABLE_NODES];
    rng_seed_all(states, qec_lfsr_t(global_seed));

    for (int j = 0; j < QEC_NUM_VARIABLE_NODES; j++) {
        if (states[j] == 0) {
            fprintf(stderr, "error: state of VN %d is zero\n", j);
            return 1;
        }
        for (int k = 0; k < j; k++) {
            if (states[j] == states[k]) {
                fprintf(stderr, "error: VN %d and VN %d have the same start state\n", k, j);
                return 1;
            }
        }
    }

    printf("#ifndef RELAY_LFSR_SEEDS_H\n#define RELAY_LFSR_SEEDS_H\n\n");
    printf("/* GENERATED by Relay_BP/gen_lfsr_seeds.cpp -- do not edit by hand.\n");
    printf("   Per-VNU 8-bit LFSR start states = rng_seed_all(states, %u) (vnu/RNG.cpp, leap-ahead\n", global_seed);
    printf("   seeding: VN j starts floor(j*255/144) steps after the global start state).\n");
    printf("   Loaded into vnu_state[j].lfsr before leg 0 of every decode. */\n\n");
    printf("#include \"../hls_types.h\"\n\n");
    printf("#define RELAY_LFSR_GLOBAL_SEED %uu\n\n", global_seed);
    printf("static const qec_lfsr_t RELAY_LFSR_SEED[%d] = {\n", QEC_NUM_VARIABLE_NODES);
    for (int j = 0; j < QEC_NUM_VARIABLE_NODES; j++) {
        if (j % 12 == 0) printf("    ");
        int last_in_line = (j % 12 == 11) || (j == QEC_NUM_VARIABLE_NODES - 1);
        printf("0x%02Xu", (unsigned)states[j].to_uint());
        if (j != QEC_NUM_VARIABLE_NODES - 1) printf(last_in_line ? "," : ", ");
        if (last_in_line) printf("\n");
    }
    printf("};\n\n#endif\n");
    return 0;
}
